"""Remove regenerable full matrices from this round's records, preserving exact cores."""
import copy
import hashlib
import json
from pathlib import Path

OUT = Path('research/prime_spectral/verification_2026_10_13_calibration')
SNAPSHOT = OUT/'source_snapshots/control_window_calibration_initial.py'


def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024*1024), b''):
            h.update(chunk)
    return h.hexdigest()


def compact():
    initial = sha(SNAPSHOT)
    events = []
    for path in sorted(OUT.glob('*_windows/C*.json')):
        old_size, original_hash = path.stat().st_size, sha(path)
        data = json.loads(path.read_text())
        if not any('matrix' in sector for sector in data['sectors']):
            continue
        for sector in data['sectors']:
            del sector['matrix']
        # The mathematical core is hashed before changing provenance or storage metadata.
        core = json.dumps(data['sectors'], sort_keys=True, separators=(',', ':')).encode()
        core_hash = hashlib.sha256(core).hexdigest()
        declared = data['source_sha256'].pop('control_window_calibration.py')
        if declared != initial:
            raise ValueError('record was not generated by the preserved initial source')
        data.setdefault('input_sha256', {})[str(SNAPSHOT)] = initial
        data['source_sha256']['compact_calibration_records.py'] = sha(Path(__file__))
        data['original_generation_source_sha256'] = initial
        data['matrix_storage'] = 'Full matrix arrays removed; reconstruct from the versioned closed-entry generator. Exact witnesses, quotient balls and pivots are unchanged.'
        data['compacted_mathematical_core_sha256'] = core_hash
        path.write_text(json.dumps(data, indent=2)+'\n')
        fresh = json.loads(path.read_text())
        if hashlib.sha256(json.dumps(fresh['sectors'], sort_keys=True, separators=(',', ':')).encode()).hexdigest() != core_hash:
            raise ArithmeticError('mathematical core changed during compaction')
        events.append({'file': str(path), 'original_sha256': original_hash,
                       'compacted_sha256': sha(path), 'original_bytes': old_size,
                       'compacted_bytes': path.stat().st_size, 'core_sha256': core_hash})
        if len(events) % 10 == 0:
            print('compacted', len(events), 'records', flush=True)
    for path in sorted(OUT.glob('*_windows/search*.json')):
        data = json.loads(path.read_text())
        for rec in data['records']:
            rec['sha256'] = sha(Path(rec['file']))
        path.write_text(json.dumps(data, indent=2)+'\n')
    result = {'status': 'generated_record_matrices_removed_exact_cores_unchanged',
              'events': events, 'snapshot_sha256': initial,
              'original_bytes': sum(e['original_bytes'] for e in events),
              'compacted_bytes': sum(e['compacted_bytes'] for e in events),
              'source_sha256': {'compact_calibration_records.py': sha(Path(__file__))}}
    (OUT/'storage_compaction.json').write_text(json.dumps(result, indent=2)+'\n')
    print(result['status'], len(events), result['original_bytes'], 'to', result['compacted_bytes'], flush=True)


if __name__ == '__main__':
    compact()
